    public function run(): void
    {
        $this->guardProduction();

        if ((int) Database::scalar('SELECT COUNT(*) FROM articles') > 0) {
            $this->info('محتوى العرض موجود بالفعل.');

            return;
        }

        $articles = $this->seedArticles();
        $faqs     = $this->seedFaqs();

        $this->info("{$articles} مقالات و{$faqs} سؤالاً شائعاً — كلها بيانات تجريبية.");
    }

    private function seedArticles(): int
    {
        $publisher = Database::scalar(
            "SELECT u.id FROM users u
               JOIN user_roles ur ON ur.user_id = u.id
               JOIN roles r ON r.id = ur.role_id
              WHERE r.code IN ('super_admin','content_editor')
           ORDER BY u.id ASC LIMIT 1",
        );

        $count = 0;

        foreach ($this->articles() as $article) {
            $categoryId = Database::scalar(
                "SELECT id FROM categories WHERE type = 'article' AND code = ? LIMIT 1",
                [$article['category']],
            );

            Database::insert(
                'INSERT INTO articles
                    (title_ar, slug, excerpt_ar, body_ar, category_id, status,
                     published_by, published_at, author_name_ar, reading_minutes,
                     is_featured, is_demo)
                 VALUES (?, ?, ?, ?, ?, ?, ?, NOW(), ?, ?, ?, 1)',
                [
                    $article['title'],
                    $article['slug'],
                    $article['excerpt'],
                    HtmlSanitizer::clean($article['body']),
                    $categoryId,
                    'published',
                    $publisher,
                    'فريق محتوى المبادرة (بيانات تجريبية)',
                    $article['minutes'],
                    $article['featured'] ? 1 : 0,
                ],
            );

            $count++;
        }

        return $count;
    }

    private function seedFaqs(): int
    {
        $count = 0;

        foreach ($this->faqs() as $index => [$section, $question, $answer]) {
            Database::insert(
                'INSERT INTO faqs
                    (section, question_ar, answer_ar, status, published_at, sort_order, is_demo)
                 VALUES (?, ?, ?, ?, NOW(), ?, 1)',
                [$section, $question, HtmlSanitizer::clean($answer), 'published', ($index + 1) * 10],
            );

            $count++;
        }

        return $count;
    }

