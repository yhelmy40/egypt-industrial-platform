    {
        return 11;
    }

    public function run(): void
    {
        foreach ($this->data() as $index => [$code, $nameAr, $nameEn, $icon, $subSectors]) {
            $sectorId = $this->upsert('sectors', [
                'code'       => $code,
                'name_ar'    => $nameAr,
                'name_en'    => $nameEn,
                'icon'       => $icon,
                'is_active'  => 1,
                'sort_order' => $index + 1,
            ], ['code']);

            foreach ($subSectors as $order => $subSector) {
                $this->upsert('sub_sectors', [
                    'sector_id'  => $sectorId,
                    'name_ar'    => $subSector,
                    'is_active'  => 1,
                    'sort_order' => $order + 1,
                ], ['sector_id', 'name_ar']);
            }
        }

        $this->info('قطاعات الأعمال والقطاعات الفرعية.');
    }

