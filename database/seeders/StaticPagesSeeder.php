<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Core\Database;

/**
 * الصفحات الثابتة | Platform static pages (§4.11, §10).
 *
 * ═══════════════════════════════════════════════════════════════════════════
 * **بذرة مرجعية لا تجريبية**، فتعمل في الإنتاج أيضاً. السبب: تذييل كل صفحة في
 * المنصة يحمل روابط «من نحن» و«الشروط» و«الخصوصية»، فغياب صفوفها يكسر روابط
 * ظاهرة لكل زائر. وجودها **شرط تشغيل** لا بيانات عرض.
 *
 * البذرة لا تكتب فوق صفحة حرّرها فريق المنصة: تُنشئ الناقص وتترك الموجود.
 *
 * ⚠ الصياغات هنا **أولية وتحتاج مراجعة قانونية** قبل الإطلاق الرسمي، ولذلك
 * يبدأ كل صفّ بـ `needs_legal_review = 1` فيظهر التنويه للزائر حتى تُراجَع.
 * ═══════════════════════════════════════════════════════════════════════════
 */
final class StaticPagesSeeder extends Seeder
{
    public function isDemo(): bool
    {
        return false;
    }

    public function order(): int
    {
        return 45;
    }

    public function run(): void
    {
        $created = 0;

        foreach ($this->pages() as $slug => $page) {
            $exists = Database::scalar(
                'SELECT 1 FROM static_pages WHERE slug = ? LIMIT 1',
                [$slug],
            );

            if ($exists !== null) {
                continue;
            }

            Database::insert(
                'INSERT INTO static_pages
                    (slug, title_ar, body_ar, status, needs_legal_review, published_at)
                 VALUES (?, ?, ?, ?, ?, NOW())',
                [$slug, $page['title'], trim($page['body']), 'published', 1],
            );

            $created++;
        }

        $this->info(
            $created === 0
                ? 'الصفحات الثابتة موجودة بالفعل.'
                : "{$created} صفحات ثابتة — صياغات أولية تحتاج مراجعة قانونية.",
        );
    }

    /** @return array<string,array{title:string,body:string}> */
    private function pages(): array
    {
        return [
            'about'   => ['title' => 'عن المبادرة', 'body' => $this->about()],
            'terms'   => ['title' => 'الشروط والأحكام', 'body' => $this->terms()],
            'privacy' => ['title' => 'سياسة الخصوصية', 'body' => $this->privacy()],
        ];
    }

