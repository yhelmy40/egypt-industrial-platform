حالاتها، ويتفق الطرفان على وسيلة الدفع والتسليم خارجها.</p>

<h2>7. إيقاف الحساب</h2>
<p>يجوز إيقاف الحساب عند مخالفة هذه الشروط، مع إبلاغ صاحبه بالسبب وإتاحة التظلّم.</p>

<h2>8. تعديل الشروط</h2>
<p>قد تُحدَّث هذه الشروط، ويُعلن التحديث على هذه الصفحة مع تاريخه.</p>
HTML;
    }

    private function privacy(): string
    {
        return <<<'HTML'
<p><strong>هذه صياغة أولية لأغراض التشغيل التجريبي، ويجب مراجعتها واعتمادها من الجهة
القانونية المختصة قبل الإطلاق الرسمي.</strong></p>

<h2>1. البيانات التي نجمعها</h2>
<ul>
<li><strong>بيانات الحساب:</strong> الاسم، البريد الإلكتروني، رقم الهاتف.</li>
<li><strong>بيانات المنشأة:</strong> الاسم القانوني والتجاري، النشاط، الموقع، بيانات التواصل.</li>
<li><strong>المستندات:</strong> ما ترفعه المنشأة لأغراض التوثيق فقط.</li>
<li><strong>بيانات الاستخدام:</strong> سجلات الدخول وعنوان IP لأغراض الأمان.</li>
</ul>
<p><strong>لا نجمع الرقم القومي ولا بيانات الحسابات البنكية</strong> في النسخة الحالية
من المنصة.</p>

<h2>2. أغراض المعالجة</h2>
<p>تُعالَج البيانات لغرض محدّد ومعلن فقط: تشغيل الحساب، توثيق المنشأة، إتاحة الخدمات،
الربط مع الجهات المموّلة ومقدّمي الخدمات بناءً على طلبك، وحماية المنصة من إساءة
الاستخدام.</p>

<h2>3. ما يظهر للعامة</h2>
<p>تظهر على الصفحة العامة للمنشأة البيانات التعريفية التي تختارها فقط. البيانات
الحسّاسة والمستندات لا تظهر للعامة إطلاقاً، ويقتصر الاطلاع عليها على فريق المراجعة
المختص.</p>

<h2>4. مشاركة البيانات</h2>
<p>لا تُشارك بياناتك مع أي جهة خارجية إلا بناءً على إجراء تبدأه أنت — مثل تقديم طلب
تمويل أو طلب خدمة — وفي حدود ما يلزم لدراسة الطلب.</p>

<h2>5. ملاحظات مقدّمي الخدمة الداخلية</h2>
<p>قد يدوّن أخصائيو مراكز تطوير الأعمال ومراجعو الجهات المموّلة ملاحظات داخلية لأغراض
العمل. هذه الملاحظات لا تظهر للمنشأة، ويقتصر الاطلاع عليها على الجهة التي كتبتها.</p>

<h2>6. مدة الاحتفاظ</h2>
<p>تُحفظ البيانات للمدة اللازمة لتحقيق غرض المعالجة ووفق مدد الاحتفاظ المُعدّة في
المنصة، ثم تُحذف أو يُزال ما يعرّف صاحبها.</p>

<h2>7. حقوقك</h2>
<ul>
<li>الاطلاع على بياناتك المحفوظة.</li>
<li>تصحيح البيانات غير الدقيقة.</li>
<li>طلب إلغاء تفعيل الحساب.</li>
<li>طلب حذف البيانات أو إزالة ما يعرّف صاحبها، في حدود ما يسمح به القانون.</li>
<li>سحب الموافقة على أغراض غير ضرورية لتشغيل الخدمة.</li>
</ul>

<h2>8. حماية البيانات</h2>
<p>تُحفظ كلمات المرور مجزّأة ولا يمكن استرجاعها. وتُخزَّن المستندات خارج نطاق الوصول
المباشر من الإنترنت، ولا تُقدَّم إلا بعد التحقق من الصلاحية، مع تسجيل كل عملية اطلاع
في سجل التدقيق.</p>

<h2>9. التواصل</h2>
<p>لأي طلب متعلق ببياناتك، تواصل مع الجهة المشغّلة للمنصة عبر بيانات التواصل المعلنة
في صفحة «اتصل بنا».</p>
HTML;
    }
