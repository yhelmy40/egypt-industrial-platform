أي معاملة.</p>

<h2>3. قرارات التمويل</h2>
<p>لا تتخذ المنصة أي قرار تمويلي ولا تُصدر موافقة نيابةً عن أي جهة. كل عرض تمويلي
يخضع لقواعد الأهلية والدراسة الائتمانية لدى الجهة المموّلة، والموافقة قرارها وحدها
يُسجَّل باسم متّخذه.</p>

<h2>4. التزامات المستخدم</h2>
<ul>
<li>تقديم بيانات صحيحة ومحدّثة عن المنشأة ونشاطها.</li>
<li>عدم نشر محتوى مخالف للقانون أو منتحل أو مضلّل.</li>
<li>المحافظة على سرية بيانات الدخول وعدم مشاركتها.</li>
<li>استخدام المنصة في الأغراض المشروعة المتصلة بنشاط المنشأة.</li>
</ul>

<h2>5. المحتوى المنشور</h2>
<p>المنشأة مسؤولة عن صحة ما تنشره من بيانات ومنتجات وأسعار. ولفريق المنصة أن يوقف
عرض أي مادة مخالفة، مع إبلاغ المنشأة بالسبب.</p>

<h2>6. الدفع والتسليم</h2>
